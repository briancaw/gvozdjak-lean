import json, sys
rows=json.load(open(sys.argv[1]))
def graceful(p,n,a,b):
    return p[0]==a and p[-1]==b and sorted(p)==list(range(n+1)) and sorted(abs(p[i]-p[i+1]) for i in range(n))==list(range(1,n+1))
byn={}
for n,a,b,p in rows:
    assert a<b and graceful(p,n,a,b); byn.setdefault(n,[]).append(p)
NMAX=max(byn)
out=["""/-
Small cases.  GENERATED by scripts/gen_small.py.

For every admissible triple `(a, b; n)` with `n ≤ 41` and `a < b` the table below contains an
explicit graceful labeling.  The table is checked by evaluating a Boolean test in Lean's kernel
(`decide +kernel`), one value of `n` at a time.
-/
import Gvozdjak.Statement

namespace Gvozdjak

set_option maxRecDepth 1000000

/-- Boolean test for `IsGraceful`. -/
def gracefulB (a b n : Nat) (p : List Nat) : Bool :=
  (p.head? == some a) && (p.getLast? == some b) &&
    p.isPerm (List.range (n + 1)) && (diffs p).isPerm (List.range' 1 n)

theorem gracefulB_sound {a b n : Nat} {p : List Nat} (h : gracefulB a b n p = true) :
    IsGraceful a b n p := by
  simp only [gracefulB, Bool.and_eq_true, beq_iff_eq, List.isPerm_iff] at h
  obtain ⟨⟨⟨h1, h2⟩, h3⟩, h4⟩ := h
  exact ⟨h1, h2, h3, h4⟩

instance (a b n : Nat) : Decidable (Admissible a b n) := by
  unfold Admissible; infer_instance
"""]
for n in range(1,NMAX+1):
    out.append(f"def tbl{n} : List (List Nat) := [\n  "+",\n  ".join("["+", ".join(map(str,p))+"]" for p in byn[n])+"]\n")
out.append("/-- The labelings available for each `n`. -/\ndef tbl : Nat → List (List Nat)")
for n in range(1,NMAX+1): out.append(f"  | {n} => tbl{n}")
out.append("  | _ => []\n")
out.append("""/-- Every admissible pair `a < b` for this `n` has a graceful labeling in the table. -/
def checkN (n : Nat) : Bool :=
  (List.range (n + 1)).all fun a => (List.range (n + 1)).all fun b =>
    !(decide (a < b) && decide (Admissible a b n)) || (tbl n).any fun p => gracefulB a b n p
""")
out.append("theorem check0 : checkN 0 = true := by decide +kernel")
for n in range(1,NMAX+1):
    out.append(f"theorem check{n} : checkN {n} = true := by decide +kernel")
out.append("\ntheorem check_all : ∀ n, n ≤ %d → checkN n = true"%NMAX)
for n in range(0,NMAX+1): out.append(f"  | {n}, _ => check{n}")
out.append(f"  | n + {NMAX+1}, h => absurd h (by omega)\n")
out.append("""/-- Every admissible triple with `n ≤ 41` and `a < b` has a graceful labeling. -/
theorem small {n a b : Nat} (hn : n ≤ %d) (hab : a < b) (h : Admissible a b n) :
    ∃ p, IsGraceful a b n p := by
  have hc := check_all n hn
  simp only [checkN, List.all_eq_true, List.mem_range] at hc
  have ha : a < n + 1 := by unfold Admissible at h; omega
  have hb : b < n + 1 := by unfold Admissible at h; omega
  have h2 := hc a ha b hb
  have h3 : (decide (a < b) && decide (Admissible a b n)) = true := by simp [hab, h]
  rw [h3] at h2
  simp only [Bool.not_true, Bool.false_or, List.any_eq_true] at h2
  obtain ⟨p, _, hp⟩ := h2
  exact ⟨p, gracefulB_sound hp⟩

end Gvozdjak
"""%NMAX)
open(sys.argv[2],"w").write("\n".join(out))
print(len(rows),"triples, nmax",NMAX)
